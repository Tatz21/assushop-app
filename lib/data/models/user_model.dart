class UserModel {
  final String id;
  final String name;
  final String role;
  final String mobile;
  final String avatarUrl;
  final String employeeId;
  final String email;

  const UserModel({
    required this.id,
    required this.name,
    required this.role,
    required this.mobile,
    required this.avatarUrl,
    required this.employeeId,
    required this.email,
  });
}
